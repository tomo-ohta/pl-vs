/**
 * 校舎の壁面の絵の配置（手で置いた形）。
 * 画面の画素の座標は「参考画像の視点（alley-0）で見える位置」。FacadePainter が壁の平面へ戻して描く。
 * 色は参考画像の同じ位置から拾った色（tools/capture.mjs --sample）。
 */

// ---------- 色 ----------
const WALL = '#152e35';
const WALL_UP = '#17343c';
const FRAME = '#0c1c22';
const PIER = '#0e2026';

/** 壁の座標で、決まった間隔の階と窓を描く（参考画像に写らない所の既定） */
function defaultFloors(
  fp: FacadePainter,
  u: [number, number],
  o: { wins: [number, number][]; transom?: number; f1?: [number, number]; pier: number; pierW: number; mull: number; panes: string[]; seed: number },
): void {
  const r = rng(o.seed);
  fp.rectF(u[0], 0, u[1], 30, WALL);
  const rows = o.f1 ? [o.f1, ...o.wins] : o.wins;
  for (const [y0, y1] of rows) {
    for (let x = u[0]; x < u[1]; x += o.mull) {
      fp.rectF(x, y0, x + o.mull, y1, o.panes[Math.floor(r() * o.panes.length)]);
      fp.lineF([x, y0], [x, y1], 0.05, FRAME);
    }
    fp.lineF([u[0], y0], [u[1], y0], 0.07, FRAME);
    fp.lineF([u[0], y1], [u[1], y1], 0.07, FRAME);
    if (o.transom !== undefined && o.f1 && y0 === o.f1[0]) fp.lineF([u[0], o.transom], [u[1], o.transom], 0.08, FRAME);
  }
  for (let x = u[0]; x < u[1]; x += o.pier) fp.rectF(x - o.pierW / 2, 0, x + o.pierW / 2, 30, PIER);
}

/** 画面の 2 点を結ぶ直線上の点（x を与えて y） */
function yAt(a: P2, b: P2, x: number): number {
  return a[1] + ((b[1] - a[1]) * (x - a[0])) / (b[0] - a[0]);
}

/** 画面の四角（上の辺 a→b、下の辺 c→d）を桟で区切った窓 */
function band(fp: FacadePainter, top: [P2, P2], bot: [P2, P2], x0: number, x1: number, color: string, cols: number[] = [], frame = 0.06): void {
  const tl: P2 = [x0, yAt(top[0], top[1], x0)];
  const tr: P2 = [x1, yAt(top[0], top[1], x1)];
  const br: P2 = [x1, yAt(bot[0], bot[1], x1)];
  const bl: P2 = [x0, yAt(bot[0], bot[1], x0)];
  fp.fill([tl, tr, br, bl], color);
  for (const x of cols) fp.line([x, yAt(top[0], top[1], x)], [x, yAt(bot[0], bot[1], x)], frame, FRAME);
  fp.line(tl, tr, frame, FRAME);
  fp.line(bl, br, frame, FRAME);
}

/** 明るい建物の映り込み（横長の窓の帯と縦の桟） */
function bldgReflect(fp: FacadePainter, poly: P2[], base: string, line: string, rows: [P2, P2][], cols: number[], yTop: number, yBot: number): void {
  fp.fill(poly, base);
  for (const [a, b] of rows) fp.line(a, b, 0.05, line);
  for (const x of cols) fp.line([x, yTop], [x, yBot], 0.04, line);
}

