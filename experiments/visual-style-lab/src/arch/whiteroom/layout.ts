/**
 * 視点の座標（中庭の軸に沿う。X = 右、d = 奥、h = 高さ）→ 場面の座標。
 * 軸は中庭の向き（視点のずれの角度は含めない）
 */
export interface Frame {
  /** 目の真下の地面の点 */
  o: [number, number];
  /** 奥の向き（場面の xz の単位ベクトル） */
  fwd: [number, number];
  /** 右の向き */
  right: [number, number];
}
export const FA: Frame = { o: [V0.eye[0], V0.eye[2]], fwd: [0, -1], right: [1, 0] };
export const FB: Frame = { o: [V1.eye[0], V1.eye[2]], fwd: [0, -1], right: [1, 0] };
export const FC: Frame = { o: [V2.eye[0], V2.eye[2]], fwd: [-1, 0], right: [0, -1] };

export function at(F: Frame, X: number, d: number): [number, number] {
  return [F.o[0] + F.fwd[0] * d + F.right[0] * X, F.o[1] + F.fwd[1] * d + F.right[1] * X];
}

