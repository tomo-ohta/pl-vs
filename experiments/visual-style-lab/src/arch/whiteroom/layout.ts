// ---------------------------------------------------------------- 日の向き（中庭ごと。部屋の中の日なたもこの向きで落とす）

/**
 * 日へ向かう単位ベクトル。A と C は同じ日（南西の上から・高さ 60°）、B だけほぼ真上（参考画像 1 の庇の影が真下に落ちるため。現実離れ）。
 * 部屋の窓・光の筒から床へ落ちる日なた（interior.ts）も同じ向きで求める（どの部屋でも同じ日が入る）
 */
export const SUN_DIR: Record<'A' | 'B' | 'C', [number, number, number]> = {
  A: [-0.354, 0.866, 0.354],
  B: [0.02, 0.995, 0.1],
  C: [-0.354, 0.866, 0.354],
};

/** 日の光が高さ 1 m 下りる間に水平に進む量 [x, z] */
export function sunTravel(c: 'A' | 'B' | 'C'): [number, number] {
  const [x, y, z] = SUN_DIR[c];
  return [-x / y, -z / y];
}
