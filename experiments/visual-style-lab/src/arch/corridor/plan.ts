/** 部屋の辺の扉 → 図の開口 */
function opening(r: RoomDef, d: RoomDef['doors'][number]): PlanOpening {
  const [x0, z0, x1, z1] = r.rect;
  const out = (s: Side): number => (s === 'n' ? z0 - d.depth / 2 : s === 's' ? z1 + d.depth / 2 : s === 'w' ? x0 - d.depth / 2 : x1 + d.depth / 2);
  const m = (d.a + d.b) / 2;
  const at: [number, number] = d.side === 'n' || d.side === 's' ? [m, out(d.side)] : [out(d.side), m];
  const kind: OpeningKind = d.leaf === 'open' ? 'opening' : d.leaf === 'swing2' ? 'fire-door' : 'door';
  return { kind, at, width: d.b - d.a, wall: d.side === 'n' || d.side === 's' ? 'x' : 'z', state: 'open', note: d.leaf === 'open' ? undefined : '近づくと開く' };
}
const openings: PlanOpening[] = [];
const seen = new Set<string>();
for (const r of ROOMS)
  for (const d of r.doors) {
    const o = opening(r, d);
    const k = `${o.at[0].toFixed(1)},${o.at[1].toFixed(1)}`;
    if (seen.has(k)) continue;
    seen.add(k);
    openings.push(o);
  }
// 4 つの防火・防煙区画の扉（参考画像の赤い扉。閉じて写る・近づくと開く）
const FIRE: [LegId, number, number][] = [
  ['A', -1.196, 1.289],
  ['B', -0.92, 1.02],
  ['C', -0.74, 0.65],
  ['D', -1.0, 0.64],
];
for (const [id, a, b] of FIRE) {
  const L = LEGS[id];
  const r = rectWorld(L, [a, L.end - 0.3, b, L.end]);
  const ns = Math.abs(Math.cos(L.yaw)) > 0.5;
  openings.push({
    kind: id === 'C' ? 'fire-door' : 'double-door',
    at: [(r[0] + r[2]) / 2, (r[1] + r[3]) / 2],
    width: b - a,
    wall: ns ? 'x' : 'z',
    state: 'closed',
    note: `${L.view} の突き当たりの赤い扉（防火・防煙区画）。参考画像では閉じている。歩いて近づくと開く`,
  });
}
